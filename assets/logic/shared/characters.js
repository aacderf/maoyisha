export function getApprovedCharacters(customCharacters = []) {
    return [
        ...BUILT_IN_CHARACTERS,
        ...customCharacters.filter((character) => character.status === "approved"),
    ];
}
export function normalizeCharacterDraft(input) {
    const timestamp = new Date().toISOString();
    return {
        id: input.id ?? `character-${cryptoSafeId()}`,
        ownerId: input.ownerId,
        name: input.name.trim(),
        faction: input.faction ?? "custom",
        gender: input.gender ?? "unknown",
        maxHp: clampNumber(input.maxHp ?? 4, 1, 8),
        tags: input.tags ?? [],
        artUrl: input.artUrl,
        artPath: input.artPath,
        description: input.description ?? "",
        skills: input.skills ?? [],
        skillText: input.skillText,
        status: input.status ?? "draft",
        rejectionReason: input.rejectionReason,
        createdAt: input.createdAt ?? timestamp,
        updatedAt: timestamp,
    };
}
function clampNumber(value, min, max) {
    return Math.min(max, Math.max(min, Math.round(value)));
}
function cryptoSafeId() {
    if (typeof crypto !== "undefined" && "randomUUID" in crypto) {
        return crypto.randomUUID();
    }
    return Math.random().toString(36).slice(2, 12);
}
